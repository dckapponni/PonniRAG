"""Dataset loading and management for PonniRAG evaluation.

This module provides utilities for loading, validating, and persisting
evaluation datasets used in the PonniRAG evaluation pipeline. It supports
two structured JSON formats and a CSV format, and exposes a unified
:func:`load_dataset` entry point that dispatches to the appropriate parser.

Supported JSON Formats:
    Format A — Minimal (suitable for pre-collected offline datasets)::

        [
          {
            "id": "q1",
            "question": "...",
            "human_answer": "...",
            "llm_answer": "..."      # optional; populated by live evaluation
          },
          ...
        ]

    Format B — Annotated (richer structure for curated datasets)::

        [
          {
            "id": "q1",
            "question": "...",
            "human_answer": "...",
            "llm_answer": "...",     # optional
            "category": "history",   # optional free-text tag
            "notes": "..."           # optional reviewer note
          },
          ...
        ]

CSV Format:
    Required columns: ``id``, ``question``, ``human_answer``.
    Optional columns: ``llm_answer``, ``category``, ``notes``.

Typical Usage::

    from dataset import load_dataset, save_dataset

    samples = load_dataset("data/eval.json")
    # ... populate llm_answer fields via the evaluation pipeline ...
    save_dataset(samples, "results/eval_with_answers.json")
"""

from __future__ import annotations

import csv
import json
import logging
from dataclasses import dataclass
from pathlib import Path
from typing import List, Optional

logger = logging.getLogger(__name__)


@dataclass
class EvalSample:
    """A single question/answer pair used during evaluation.

    This dataclass represents one unit of evaluation data, pairing a
    natural-language question with a human-authored reference answer and,
    optionally, an answer generated by the LLM under evaluation.

    Attributes:
        id (str): Unique identifier for the sample. Auto-generated as
            ``"sample_<index>"`` when not present in the source file.
        question (str): The natural-language question being evaluated.
        human_answer (str): The authoritative reference answer provided
            by a human annotator.
        llm_answer (Optional[str]): The answer produced by the LLM under
            evaluation. ``None`` if the sample has not yet passed through
            the live evaluation pipeline. Defaults to ``None``.
        category (Optional[str]): A free-text tag grouping this sample by
            topic or domain (e.g. ``"history"``, ``"science"``).
            Defaults to ``None``.
        notes (Optional[str]): Reviewer remarks or any supplementary
            context about this sample. Defaults to ``None``.

    Example::

        sample = EvalSample(
            id="q1",
            question="What is the capital of France?",
            human_answer="Paris",
            llm_answer="Paris",
            category="geography",
        )
        print(sample.is_ready())  # True
    """

    id: str
    question: str
    human_answer: str
    llm_answer: Optional[str] = None  # filled by live evaluation if absent
    category: Optional[str] = None
    notes: Optional[str] = None

    def is_ready(self) -> bool:
        """Check whether both reference and system answers are present.

        A sample is considered *ready* for scoring only when it carries
        a non-empty ``human_answer`` **and** a non-empty ``llm_answer``.
        Samples loaded from files that omit ``llm_answer`` will return
        ``False`` until the live evaluation pipeline populates that field.

        Returns:
            bool: ``True`` if both ``human_answer`` and ``llm_answer``
            are non-empty strings; ``False`` otherwise.

        Example::

            sample = EvalSample(id="q1", question="...", human_answer="Paris")
            sample.is_ready()        # False — llm_answer is None

            sample.llm_answer = "Paris"
            sample.is_ready()        # True
        """
        return bool(self.human_answer) and bool(self.llm_answer)

    def to_dict(self) -> dict:
        """Serialise the sample to a plain dictionary.

        Converts all fields to a ``dict`` suitable for JSON serialisation
        or downstream processing. Fields that are ``None`` are preserved
        as ``None`` (serialised as JSON ``null``).

        Returns:
            dict: A dictionary with keys ``"id"``, ``"question"``,
            ``"human_answer"``, ``"llm_answer"``, ``"category"``, and
            ``"notes"``.

        Example::

            sample = EvalSample(id="q1", question="...", human_answer="Paris")
            d = sample.to_dict()
            # {"id": "q1", "question": "...", "human_answer": "Paris",
            #  "llm_answer": None, "category": None, "notes": None}
        """
        return {
            "id": self.id,
            "question": self.question,
            "human_answer": self.human_answer,
            "llm_answer": self.llm_answer,
            "category": self.category,
            "notes": self.notes,
        }


def load_dataset(path: str | Path) -> List[EvalSample]:
    """Load evaluation samples from a JSON or CSV file.

    Acts as the primary entry point for dataset ingestion. Detects the
    file format from the extension and delegates to the appropriate
    internal parser (:func:`_load_json` or :func:`_load_csv`).

    Samples that are missing a ``human_answer`` are **skipped** with a
    ``WARNING``-level log message because they cannot participate in
    answer-quality scoring. Samples that are missing an ``llm_answer``
    are **kept** so the live evaluation pipeline can populate them later.

    Args:
        path (str | Path): Absolute or relative path to the dataset file.
            Supported extensions: ``.json``, ``.csv``.

    Returns:
        List[EvalSample]: A list of successfully parsed and validated
        :class:`EvalSample` objects, in the order they appear in the
        source file.

    Raises:
        FileNotFoundError: If no file exists at the specified *path*.
        ValueError: If the file extension is neither ``.json`` nor
            ``.csv``, or if required structural constraints (e.g. top-level
            JSON array, mandatory CSV columns) are violated.

    Example::

        samples = load_dataset("data/eval.json")
        ready = [s for s in samples if s.is_ready()]
        print(f"{len(ready)}/{len(samples)} samples ready for scoring")
    """
    path = Path(path)
    if not path.exists():
        raise FileNotFoundError(f"Dataset file not found: {path}")

    suffix = path.suffix.lower()
    if suffix == ".json":
        return _load_json(path)
    elif suffix == ".csv":
        return _load_csv(path)
    else:
        raise ValueError(f"Unsupported dataset format '{suffix}'. Use .json or .csv.")


def _load_json(path: Path) -> List[EvalSample]:
    """Parse a JSON array of sample objects into :class:`EvalSample` instances.

    Reads the file at *path*, validates the top-level structure, and
    iterates over each element. Entries that are not ``dict`` objects or
    that lack required fields are skipped with a warning rather than
    raising an exception, allowing partial datasets to be processed.

    The ``"id"`` field is auto-generated as ``"sample_<1-based index>"``
    when absent. Empty or whitespace-only ``llm_answer`` values are
    normalised to ``None``.

    Args:
        path (Path): Path to a UTF-8 encoded ``.json`` file whose
            top-level value is a JSON array of objects.

    Returns:
        List[EvalSample]: Ordered list of valid :class:`EvalSample`
        objects. Entries with an empty ``question`` or ``human_answer``
        are excluded from the result.

    Raises:
        ValueError: If the top-level JSON value is not a ``list``.
        json.JSONDecodeError: If the file content is not valid JSON
            (propagated from :func:`json.load`).

    Note:
        This function is intended for internal use. External callers
        should use :func:`load_dataset` instead.
    """
    with path.open(encoding="utf-8") as fh:
        raw = json.load(fh)

    if not isinstance(raw, list):
        raise ValueError(
            f"JSON dataset must be a top-level array, got {type(raw).__name__}."
        )

    samples: List[EvalSample] = []
    for idx, item in enumerate(raw):
        if not isinstance(item, dict):
            logger.warning("Skipping non-dict entry at index %d", idx)
            continue

        # Auto-generate id if absent
        sample_id = str(item.get("id", f"sample_{idx + 1}"))
        question = item.get("question", "").strip()
        human_answer = item.get("human_answer", "").strip()

        if not question:
            logger.warning("Skipping entry %s — missing 'question' field", sample_id)
            continue
        if not human_answer:
            logger.warning(
                "Skipping entry %s — missing 'human_answer' field", sample_id
            )
            continue

        samples.append(
            EvalSample(
                id=sample_id,
                question=question,
                human_answer=human_answer,
                llm_answer=(item.get("llm_answer") or "").strip() or None,
                category=item.get("category"),
                notes=item.get("notes"),
            )
        )

    logger.info("Loaded %d valid samples from %s", len(samples), path)
    return samples


def _load_csv(path: Path) -> List[EvalSample]:
    """Parse a CSV file with a header row into :class:`EvalSample` instances.

    Opens the file at *path* using :class:`csv.DictReader` and converts
    each data row into an :class:`EvalSample`. Presence of the mandatory
    columns ``"question"`` and ``"human_answer"`` is validated against the
    header before iterating rows. Rows with empty values in either
    mandatory column are skipped with a warning.

    The ``"id"`` column is optional; missing values default to
    ``"sample_<1-based row index>"``. Empty or whitespace-only
    ``llm_answer`` values are normalised to ``None``.

    Args:
        path (Path): Path to a UTF-8 encoded ``.csv`` file with a header
            row. Required columns: ``question``, ``human_answer``.
            Optional columns: ``id``, ``llm_answer``, ``category``,
            ``notes``.

    Returns:
        List[EvalSample]: Ordered list of valid :class:`EvalSample`
        objects corresponding to non-empty CSV rows.

    Raises:
        ValueError: If the CSV header is missing one or more required
            columns (``question`` or ``human_answer``).

    Note:
        This function is intended for internal use. External callers
        should use :func:`load_dataset` instead.
    """
    samples: List[EvalSample] = []
    with path.open(encoding="utf-8", newline="") as fh:
        reader = csv.DictReader(fh)
        required = {"question", "human_answer"}
        if reader.fieldnames:
            missing = required - set(reader.fieldnames)
            if missing:
                raise ValueError(
                    f"CSV is missing required columns: {missing}. "
                    f"Found: {reader.fieldnames}"
                )
        for idx, row in enumerate(reader):
            question = row.get("question", "").strip()
            human_answer = row.get("human_answer", "").strip()
            if not question or not human_answer:
                logger.warning(
                    "Skipping CSV row %d — empty question or human_answer", idx
                )
                continue
            sample_id = row.get("id", f"sample_{idx + 1}").strip()
            llm_raw = (row.get("llm_answer") or "").strip()
            samples.append(
                EvalSample(
                    id=sample_id,
                    question=question,
                    human_answer=human_answer,
                    llm_answer=llm_raw or None,
                    category=row.get("category"),
                    notes=row.get("notes"),
                )
            )

    logger.info("Loaded %d valid samples from CSV %s", len(samples), path)
    return samples


def save_dataset(samples: List[EvalSample], path: str | Path) -> None:
    """Persist a list of :class:`EvalSample` objects to a JSON file.

    Serialises each sample via :meth:`EvalSample.to_dict` and writes the
    resulting array to *path* as pretty-printed JSON (2-space indent).
    Non-ASCII characters are preserved as-is (``ensure_ascii=False``).
    Any missing parent directories are created automatically.

    This function is particularly useful for checkpointing results after
    the live evaluation pipeline has populated ``llm_answer`` fields, so
    that evaluated answers can be stored alongside the original questions
    and reference answers without re-running inference.

    Args:
        samples (List[EvalSample]): The list of :class:`EvalSample`
            objects to serialise. An empty list produces a valid JSON
            file containing an empty array (``[]``).
        path (str | Path): Destination file path. The file and any
            missing parent directories are created if they do not exist.
            Must have a ``.json`` extension for downstream compatibility,
            though this is not enforced by the function itself.

    Returns:
        None

    Example::

        samples = load_dataset("data/eval.csv")
        # ... run evaluation pipeline to fill llm_answer fields ...
        save_dataset(samples, "results/eval_scored.json")
    """
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8") as fh:
        json.dump([s.to_dict() for s in samples], fh, ensure_ascii=False, indent=2)
    logger.info("Saved %d samples to %s", len(samples), path)
